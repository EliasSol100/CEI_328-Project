const APP_COOKIE_CONSENT_NAME = "athina_cookie_consent";

function readNamedCookie(name) {
    const encodedName = encodeURIComponent(name) + "=";
    const parts = document.cookie ? document.cookie.split("; ") : [];

    for (let index = 0; index < parts.length; index += 1) {
        if (parts[index].indexOf(encodedName) === 0) {
            return decodeURIComponent(parts[index].slice(encodedName.length));
        }
    }

    return "";
}

function readCookieConsent() {
    const rawValue = readNamedCookie(APP_COOKIE_CONSENT_NAME);
    if (!rawValue) {
        return null;
    }

    try {
        return JSON.parse(rawValue);
    } catch (error) {
        return null;
    }
}

function canUsePreferenceStorage() {
    const consent = readCookieConsent();
    return Boolean(consent && consent.preferences);
}

function readPreferenceStorage(key) {
    if (!canUsePreferenceStorage()) {
        return null;
    }

    try {
        return window.localStorage.getItem(key);
    } catch (error) {
        return null;
    }
}

function writePreferenceStorage(key, value) {
    try {
        if (canUsePreferenceStorage()) {
            window.localStorage.setItem(key, value);
            return;
        }

        window.localStorage.removeItem(key);
    } catch (error) {
        // Ignore localStorage access issues silently.
    }
}

function removePreferenceStorage(key) {
    try {
        window.localStorage.removeItem(key);
    } catch (error) {
        // Ignore localStorage access issues silently.
    }
}

window.appPreferenceStorageAllowed = canUsePreferenceStorage;

let currentLanguage = readPreferenceStorage("language") || "en";

function replaceParams(text, params = {}) {
    let output = String(text ?? "");
    Object.keys(params || {}).forEach((key) => {
        output = output.split(`{${key}}`).join(String(params[key] ?? ""));
    });
    return output;
}

function appTranslate(key, params = {}, lang = currentLanguage) {
    const map = translations[lang] || translations.en || {};
    const fallback = translations.en || {};
    return replaceParams(map[key] ?? fallback[key] ?? key, params);
}

function getPairValue(element, prefix, lang) {
    const exact = element.getAttribute(`${prefix}-${lang}`);
    if (exact !== null) {
        return exact;
    }
    return element.getAttribute(`${prefix}-en`);
}

function applyPairTranslations(lang) {
    document.querySelectorAll("[data-text-en][data-text-el]").forEach((element) => {
        const value = getPairValue(element, "data-text", lang);
        if (value !== null) {
            element.textContent = value;
        }
    });

    document.querySelectorAll("[data-html-en][data-html-el]").forEach((element) => {
        const value = getPairValue(element, "data-html", lang);
        if (value !== null) {
            element.innerHTML = value;
        }
    });

    document.querySelectorAll("[data-placeholder-en][data-placeholder-el]").forEach((element) => {
        const value = getPairValue(element, "data-placeholder", lang);
        if (value !== null) {
            element.setAttribute("placeholder", value);
        }
    });

    document.querySelectorAll("[data-title-en][data-title-el]").forEach((element) => {
        const value = getPairValue(element, "data-title", lang);
        if (value !== null) {
            element.setAttribute("title", value);
        }
    });

    document.querySelectorAll("[data-aria-label-en][data-aria-label-el]").forEach((element) => {
        const value = getPairValue(element, "data-aria-label", lang);
        if (value !== null) {
            element.setAttribute("aria-label", value);
        }
    });

    document.querySelectorAll("[data-value-en][data-value-el]").forEach((element) => {
        const value = getPairValue(element, "data-value", lang);
        if (value !== null) {
            element.value = value;
        }
    });

    if (document.body) {
        const pageTitle = getPairValue(document.body, "data-page-title", lang);
        if (pageTitle !== null) {
            document.title = pageTitle;
        }
    }
}

function setLanguage(lang) {
    currentLanguage = lang;
    writePreferenceStorage("language", lang);

    document.querySelectorAll("[data-translate]").forEach((element) => {
        const key = element.getAttribute("data-translate");
        if (key) {
            element.textContent = appTranslate(key, {}, lang);
        }
    });

    document.querySelectorAll("[data-translate-placeholder]").forEach((element) => {
        const key = element.getAttribute("data-translate-placeholder");
        if (key) {
            element.setAttribute("placeholder", appTranslate(key, {}, lang));
        }
    });

    document.querySelectorAll("[data-translate-title]").forEach((element) => {
        const key = element.getAttribute("data-translate-title");
        if (key) {
            element.setAttribute("title", appTranslate(key, {}, lang));
        }
    });

    document.querySelectorAll("[data-product-name]").forEach((element) => {
        const value = lang === "el"
            ? element.getAttribute("data-name-el")
            : element.getAttribute("data-name-en");
        if (value) {
            element.textContent = value;
        }
    });

    applyPairTranslations(lang);

    const langDisplay = document.querySelector(".language-selector span");
    if (langDisplay) {
        langDisplay.textContent = lang === "el" ? "ΕΛ" : "EN";
    }

    document.documentElement.lang = lang;
    document.dispatchEvent(new CustomEvent("app:languagechange", { detail: { lang } }));
}

window.appTranslate = appTranslate;
window.appCurrentLanguage = function () {
    return currentLanguage;
};
window.appSetLanguage = setLanguage;

document.addEventListener("app:cookieconsentchange", () => {
    if (!canUsePreferenceStorage()) {
        removePreferenceStorage("language");
    }
});

document.addEventListener("DOMContentLoaded", () => {
    setLanguage(currentLanguage);

    const languageSelector = document.querySelector(".language-selector");
    if (languageSelector) {
        languageSelector.addEventListener("click", (event) => {
            event.preventDefault();
            event.stopPropagation();
            setLanguage(currentLanguage === "en" ? "el" : "en");
        });

        languageSelector.addEventListener("keydown", (event) => {
            if (event.key === "Enter" || event.key === " ") {
                event.preventDefault();
                setLanguage(currentLanguage === "en" ? "el" : "en");
            }
        });

        languageSelector.style.cursor = "pointer";
        if (!languageSelector.hasAttribute("title")) {
            languageSelector.setAttribute("title", "Click to change language");
        }
    }
});
